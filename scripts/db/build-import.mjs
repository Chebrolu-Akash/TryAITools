#!/usr/bin/env node
// Generates idempotent SQL to import src/data/tools.json (+ the curated snapshot) into D1.
//   node scripts/db/build-import.mjs --env preview [--out db/import/out]
// Read-only with respect to the repo's data: writes only into --out. It never talks to Cloudflare.
// Re-running the generated SQL is safe: every INSERT uses ON CONFLICT DO NOTHING, so admin edits made
// after the first import are never overwritten.
import { mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assignImportKeys, assignSlugs, importIssue } from "./slugs.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith("--") ? [...acc, [a.slice(2), all[i + 1]?.startsWith("--") || all[i + 1] === undefined ? "true" : all[i + 1]]] : acc), []),
);
const env = args.env;
if (!["preview", "local"].includes(env)) {
  console.error('Refusing to run: --env must be "preview" or "local". Production imports are not enabled until explicitly approved.');
  process.exit(2);
}
const out = resolve(args.out ?? "db/import/out");
const CHUNK = 400;

const data = JSON.parse(readFileSync(resolve(here, "../../src/data/tools.json"), "utf8"));
const snapshot = JSON.parse(readFileSync(resolve(here, "curated-snapshot.json"), "utf8")).items;

const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  const s = String(v);
  if (/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(s)) throw new Error(`Control character in value: ${JSON.stringify(s.slice(0, 40))}`);
  return `'${s.replace(/'/g, "''")}'`;
};
const j = (v) => (v === null || v === undefined ? "NULL" : q(JSON.stringify(v)));

const categories = data.categories;
const tools = data.tools;
const keys = assignImportKeys(tools);
const slugs = assignSlugs(tools, categories);
const catByName = new Map(categories.map((c) => [c.name, c]));
const curatedByKey = new Map(snapshot.map((s) => [s.key, s]));
const curatedKey = (t) => t.name.replace(/ \(.+\)$/, "").toLowerCase();

const problems = [];
const toolStmts = [];
const curatedStmts = [];
let curatedRows = 0;

tools.forEach((t, i) => {
  const cat = catByName.get(t.category);
  if (!cat) {
    problems.push({ key: keys[i], problem: `unknown category: ${t.category}` });
    return;
  }
  const issue = importIssue(t);
  const cur = curatedByKey.get(curatedKey(t));
  const isPrimary = !!cur?.primary && cur.primary.name === t.name && cur.primary.category === t.category;
  // Flagged rows are imported but kept out of public view: status draft + needs_review.
  const status = issue ? "draft" : "published";
  const indexing = isPrimary && !issue ? "index" : "noindex";
  const url = issue === "placeholder_name" || issue === "invalid_url" || issue === "missing_url" ? (t.url?.trim() || null) : t.url.trim();
  toolStmts.push(
    `INSERT INTO tools (id,slug,name,url,category_id,subcategory,status,indexing,needs_review,import_issue,content_source,sort_order) VALUES (${q(keys[i])},${q(slugs[i])},${q(t.name)},${q(url)},${q(cat.id ?? cat.slug)},${q(t.subcategory || null)},${q(status)},${q(indexing)},${issue ? 1 : 0},${q(issue)},${cur ? "'curated'" : "'import'"},${i}) ON CONFLICT(id) DO NOTHING;`,
  );
  if (cur && !issue) {
    const c = cur.content;
    curatedRows++;
    // Only fills a curated row that is still untouched by an admin (content_source = 'curated' AND tagline IS NULL).
    curatedStmts.push(
      `UPDATE tools SET tagline=${q(c.tagline)},overview=${q(c.overview)},best_for=${q(c.bestFor)},features=${j(c.features)},pros=${j(c.pros)},limits=${j(c.limits)},steps=${j(c.steps)},tips=${j(c.tips)} WHERE id=${q(keys[i])} AND content_source='curated' AND tagline IS NULL;`,
    );
  }
});
if (problems.length) {
  console.error("Import blocked by data problems:", problems);
  process.exit(1);
}

const catStmts = categories.map(
  (c, i) => `INSERT INTO categories (id,slug,name,subcategories,sort_order) VALUES (${q(c.slug)},${q(c.slug)},${q(c.name)},${j(c.subcategories ?? [])},${i}) ON CONFLICT(id) DO NOTHING;`,
);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const files = [];
const write = (name, stmts) => {
  writeFileSync(resolve(out, name), `-- generated by scripts/db/build-import.mjs (env=${env}); do not edit\n${stmts.join("\n")}\n`);
  files.push(name);
};
write("00_environment.sql", [`INSERT INTO meta (key,value) VALUES ('environment',${q(env)}) ON CONFLICT(key) DO NOTHING;`]);
write("01_categories.sql", catStmts);
for (let i = 0; i < toolStmts.length; i += CHUNK) write(`02_tools_${String(i / CHUNK + 1).padStart(2, "0")}.sql`, toolStmts.slice(i, i + CHUNK));
write("03_curated.sql", curatedStmts);

const flagged = tools.map((t, i) => ({ key: keys[i], name: t.name, url: t.url, category: t.category, issue: importIssue(t) })).filter((x) => x.issue);
const report = {
  env,
  generatedFiles: files,
  expected: { categories: categories.length, tools: tools.length, flagged: flagged.length, published: tools.length - flagged.length, indexable: toolStmts.length && snapshot.filter((s) => s.primary).length, curatedRows },
  repeatedJsonIds: keys.filter((k) => k.includes("#")),
  flagged,
};
writeFileSync(resolve(out, "report.json"), JSON.stringify(report, null, 2));
writeFileSync(resolve(out, "slugs.json"), JSON.stringify(Object.fromEntries(keys.map((k, i) => [k, slugs[i]])), null, 0));
console.log(JSON.stringify({ out, ...report.expected, repeatedJsonIds: report.repeatedJsonIds, files: files.length }, null, 2));
