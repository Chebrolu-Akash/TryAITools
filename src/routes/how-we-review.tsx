// src/lib/admin/index-gate.ts, src/lib/news). Owner-specific facts are added only when the owner provides them.
export const Route = createFileRoute("/how-we-review")({
  head: () =>
    pageHead({
      title: "How We Review AI Tools | TryAITools",
      description:
        "How TryAITools reviews AI tools: what we check, how we verify pricing, why some listings aren't reviewed yet and how AI News summaries are written.",
      path: "/how-we-review",
    }),
  component: () => (
    <LegalPage
      title="How we review AI tools"
      intro="What “reviewed” means on TryAITools, what we check, and what we don’t do — so you can decide how much to rely on each page."
    >
      <section>
        <h2>Two kinds of tool pages</h2>
        <ul>
          <li>
            <strong>Reviewed tool pages</strong> have been checked against the tool&apos;s official
            website. They describe what the tool does, its key features, advantages, limitations and
            pricing. These pages are open to search engines.
          </li>
          <li>
            <strong>Directory listings</strong> show a tool&apos;s name, category and official
            website with general guidance for that category. They say “We haven&apos;t reviewed this
            tool in detail yet” and are kept out of search results until they are reviewed.
          </li>
        </ul>
      </section>
      <section>
        <h2>What we check before a page counts as reviewed</h2>
        <ul>
          <li>
            <strong>The product and its website.</strong> The official URL must work and lead to the
            named product.
          </li>
          <li>
            <strong>Features, advantages and limitations.</strong> Each one must be supported by the
            tool&apos;s own official pages. If the official pages don&apos;t support a claim, it is
            left out. We don&apos;t pad pages with invented pros or cons.
          </li>
          <li>
            <strong>Pricing.</strong> Taken from the official pricing page, with a link to it and
            the date it was checked. When pricing can&apos;t be confirmed, the page says so instead
            of guessing. Prices change often: the official site is always the final word.
          </li>
          <li>
            <strong>Category.</strong> Each tool has one page, placed in the category that best
            matches its main use. A tool that fits several categories is listed in each of them, all
            pointing to the same page.
          </li>
        </ul>
      </section>
      <section>
        <h2>How AI is used</h2>
        <p>
          We use AI (Google Gemini) to help draft tool pages from the text of each tool&apos;s
          official website. Every draft claim must quote the official page that supports it; claims
          without a matching quote are removed automatically, and an editor approves each page
          before it is published. Drafts that can&apos;t be verified are set aside for manual
          review.
        </p>
      </section>
      <section>
        <h2>What we don&apos;t do</h2>
        <ul>
          <li>We don&apos;t publish star ratings or user reviews we haven&apos;t collected.</li>
          <li>We don&apos;t invent features, prices, customers or statistics.</li>
          <li>
            Affiliate commissions don&apos;t decide whether a tool is listed, how it is categorised
            or what we write. See our <a href="/affiliate-disclosure">affiliate disclosure</a>.
          </li>
        </ul>
      </section>
      <section>
        <h2>How AI News is written</h2>
        <p>
          AI News pages are short summaries generated by AI (Google Gemini) from announcements
          published by official AI company blogs and research sources. Each summary uses only the
          source&apos;s own text, is labelled as AI-generated and links to the original article —
          read the source for the full story.
        </p>
      </section>
    </LegalPage>
  ),
});
