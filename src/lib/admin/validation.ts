import * as z from "zod";

// Server-side validation for every admin write. The browser's checks are a convenience only.
// All text is stored as PLAIN TEXT and rendered by React (which escapes it); Markdown goes through
// src/lib/markdown.ts, which never emits raw HTML.

// eslint-disable-next-line no-control-regex
const CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/;

const text = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Must be at most ${max} characters`)
    .refine((v) => !CONTROL.test(v), "Contains control characters");

const optText = (max: number) =>
  text(max)
    .optional()
    .nullable()
    .transform((v) => (v ? v : null));

export const isSafeHttpUrl = (value: string): boolean => {
  if (value.length > 2048 || CONTROL.test(value)) return false;
  try {
    const u = new URL(value);
    return (
      (u.protocol === "https:" || u.protocol === "http:") &&
      !u.username &&
      !u.password &&
      u.hostname.includes(".")
    );
  } catch {
    return false;
  }
};

const optUrl = z
  .string()
  .trim()
  .optional()
  .nullable()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || isSafeHttpUrl(v), "Must be a valid http(s) URL");

const list = (maxItems: number, maxLen: number) =>
  z
    .array(text(maxLen))
    .max(maxItems, `At most ${maxItems} items`)
    .optional()
    .nullable()
    .transform((v) => (v && v.filter(Boolean).length ? v.filter(Boolean) : null));

export const slugSchema = z
  .string()
  .trim()
  .min(2, "Slug must be at least 2 characters")
  .max(80, "Slug must be at most 80 characters")
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "Use lowercase letters, numbers and single hyphens only");

// RFC 4122 v4 UUID generated by the browser once per "new" form; makes create requests idempotent.
export const clientIdSchema = z
  .string()
  .regex(
    /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i,
    "Invalid client id",
  );

const tags = z
  .array(text(40))
  .max(15)
  .optional()
  .transform((v) => (v ?? []).filter(Boolean));

export const toolFields = {
  name: text(120).refine((v) => v.length > 0, "Name is required"),
  display_name: optText(120),
  url: optUrl,
  category_id: z.string().trim().min(1, "Category is required").max(80),
  subcategory: optText(120),
  tags,
  logo_url: optUrl,
  tagline: optText(200),
  overview: optText(4000),
  best_for: optText(300),
  features: list(20, 300),
  pros: list(20, 300),
  limits: list(20, 300),
  steps: list(20, 400),
  tips: list(20, 400),
  pricing_note: optText(300),
  pricing_source: optText(300),
  platforms: list(15, 60),
  seo_title: optText(70),
  seo_description: optText(170),
  canonical_url: optUrl,
  og_image_url: optUrl,
  indexing: z.enum(["index", "noindex"]),
};

export const toolCreateSchema = z
  .object({ client_id: clientIdSchema, slug: slugSchema, ...toolFields })
  .strict();
export const toolUpdateSchema = z
  .object({ updated_at: z.string().min(10).max(40), ...toolFields })
  .strict(); // slug is immutable in Stage 3

export const TOOL_ACTIONS = [
  "publish",
  "unpublish",
  "send_to_review",
  "archive",
  "restore",
  "flag_needs_review",
  "clear_needs_review",
] as const;
export const toolActionSchema = z
  .object({ action: z.enum(TOOL_ACTIONS), updated_at: z.string().min(10).max(40) })
  .strict();

const categoryFields = {
  name: text(80).refine((v) => v.length > 0, "Name is required"),
  description: optText(500),
  subcategories: z
    .array(text(120).refine((v) => v.length > 0, "Empty subcategory"))
    .max(40)
    .refine(
      (v) => new Set(v.map((s) => s.toLowerCase())).size === v.length,
      "Subcategories must be unique",
    ),
  sort_order: z.number().int().min(0).max(100000),
  status: z.enum(["draft", "published", "archived"]),
  indexing: z.enum(["index", "noindex"]),
  seo_title: optText(70),
  seo_description: optText(170),
};
export const categoryCreateSchema = z.object({ slug: slugSchema, ...categoryFields }).strict();
export const categoryUpdateSchema = z
  .object({ updated_at: z.string().min(10).max(40), ...categoryFields })
  .strict();

const blogFields = {
  title: text(160).refine((v) => v.length > 0, "Title is required"),
  excerpt: optText(300),
  body_md: z
    .string()
    .max(100_000, "Body is too long")
    .refine((v) => !CONTROL.test(v.replace(/[\t\n\r]/g, "")), "Contains control characters"),
  author_name: optText(80),
  tags,
  seo_title: optText(70),
  seo_description: optText(170),
  canonical_url: optUrl,
};
export const blogCreateSchema = z
  .object({ client_id: clientIdSchema, slug: slugSchema, ...blogFields })
  .strict();
export const blogUpdateSchema = z
  .object({ updated_at: z.string().min(10).max(40), ...blogFields })
  .strict();
export const BLOG_ACTIONS = ["publish", "unpublish", "archive", "restore"] as const;
export const blogActionSchema = z
  .object({ action: z.enum(BLOG_ACTIONS), updated_at: z.string().min(10).max(40) })
  .strict();

// Permanent deletion: the caller must echo the record's slug (typed by the owner) and its current updated_at.
export const deleteSchema = z
  .object({ updated_at: z.string().min(10).max(40), confirm: z.string().max(80) })
  .strict();

export type FieldErrors = Record<string, string>;
export function fieldErrors(err: z.ZodError): FieldErrors {
  const out: FieldErrors = {};
  for (const issue of err.issues) {
    const key = issue.path.join(".") || "_";
    if (!(key in out)) out[key] = issue.message;
  }
  return out;
}
