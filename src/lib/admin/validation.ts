import * as z from "zod";

// Server-side validation for every admin write. The browser's checks are a convenience only.
// All text is stored as PLAIN TEXT and rendered by React (which escapes it); Markdown goes through
// src/lib/markdown.ts, which never emits raw HTML.

// eslint-disable-next-line no-control-regex
const CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/;

const text = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Must be at most ${max} characters`)
    .refine((v) => !CONTROL.test(v), "Contains control characters");

const optText = (max: number) =>
  text(max)
    .optional()
    .nullable()
    .transform((v) => (v ? v : null));

export const isSafeHttpUrl = (value: string): boolean => {
  if (value.length > 2048 || CONTROL.test(value)) return false;
  try {
    const u = new URL(value);
    return (
      (u.protocol === "https:" || u.protocol === "http:") &&
      !u.username &&
      !u.password &&
      u.hostname.includes(".")
    );
  } catch {
    return false;
  }
};

const optUrl = z
  .string()
  .trim()
  .optional()
  .nullable()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || isSafeHttpUrl(v), "Must be a valid http(s) URL");

const list = (maxItems: number, maxLen: number) =>
  z
    .array(text(maxLen))
    .max(maxItems, `At most ${maxItems} items`)
    .optional()
    .nullable()
    .transform((v) => (v && v.filter(Boolean).length ? v.filter(Boolean) : null));

export const slugSchema = z
  .string()
  .trim()
  .min(2, "Slug must be at least 2 characters")
  .max(80, "Slug must be at most 80 characters")
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "Use lowercase letters, numbers and single hyphens only");

